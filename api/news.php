<?php

header('Content-Type: application/json');
header('Access-Control-Allow-Origin: *');

/*
|--------------------------------------------------------------------------
| Get Actor ID
|--------------------------------------------------------------------------
*/

$actor_id = $_GET['id'] ?? 'nm0366389';

/*
|--------------------------------------------------------------------------
| API URL
|--------------------------------------------------------------------------
*/

$url =
"https://imdb232.p.rapidapi.com/api/actors/get-related-news?limit=25&nm=$actor_id";

/*
|--------------------------------------------------------------------------
| Initialize cURL
|--------------------------------------------------------------------------
*/

$curl = curl_init();

/*
|--------------------------------------------------------------------------
| cURL Options
|--------------------------------------------------------------------------
*/

curl_setopt_array($curl, [

    CURLOPT_URL => $url,

    CURLOPT_RETURNTRANSFER => true,

    CURLOPT_FOLLOWLOCATION => true,

    CURLOPT_TIMEOUT => 30,

    CURLOPT_HTTPHEADER => [

        "x-rapidapi-host: imdb232.p.rapidapi.com",

        /*
        |--------------------------------------------------------------------------
        | PUT YOUR API KEY HERE
        |--------------------------------------------------------------------------
        */

        "x-rapidapi-key: YOUR_RAPID_API_KEY"
    ]
]);

/*
|--------------------------------------------------------------------------
| Execute Request
|--------------------------------------------------------------------------
*/

$response = curl_exec($curl);

/*
|--------------------------------------------------------------------------
| Error Check
|--------------------------------------------------------------------------
*/

$error = curl_error($curl);

/*
|--------------------------------------------------------------------------
| HTTP Status
|--------------------------------------------------------------------------
*/

$http_code =
curl_getinfo(
    $curl,
    CURLINFO_HTTP_CODE
);

/*
|--------------------------------------------------------------------------
| Close cURL
|--------------------------------------------------------------------------
*/

curl_close($curl);

/*
|--------------------------------------------------------------------------
| Handle cURL Error
|--------------------------------------------------------------------------
*/

if($error){

    echo json_encode([

        'status' => false,

        'message' => $error
    ]);

    exit;
}

/*
|--------------------------------------------------------------------------
| API Failed
|--------------------------------------------------------------------------
*/

if($http_code !== 200){

    echo json_encode([

        'status' => false,

        'message' => 'API Request Failed',

        'http_code' => $http_code
    ]);

    exit;
}

/*
|--------------------------------------------------------------------------
| Return API Response
|--------------------------------------------------------------------------
*/

echo $response;